import { spawn } from 'node:child_process'
import type { ChildProcessWithoutNullStreams } from 'node:child_process'
import { existsSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import http from 'node:http'
import type { TunnelSnapshot } from '@shared/types'
import { configureAuthtoken, detectNgrok, managedBinDir } from './ngrok'

export interface TunnelOptions {
  port: number
  ngrokPath: string | null
  authtoken: string
  protectToken: string
  domain: string
  protect: boolean
}

export function writeTrafficPolicy(token: string): string {
  const dir = managedBinDir()
  const path = join(dir, 'portal-policy.yml')
  const yaml = `# Generated by OpenCode Portal. Requests without the portal token are rejected at the ngrok edge.
on_http_request:
  - expressions:
      - "!hasReqHeader('Authorization') || getReqHeader('Authorization')[0] != 'Bearer ${token}'"
    actions:
      - type: deny
        config:
          status_code: 401
`
  writeFileSync(path, yaml, 'utf8')
  return path
}

function localApiTunnels(port: number, timeout = 1500): Promise<string | null> {
  return new Promise((resolve) => {
    const request = http.get(
      { host: '127.0.0.1', port: 4040, path: '/api/tunnels', timeout },
      (res) => {
        const chunks: Buffer[] = []
        res.on('data', (chunk) => chunks.push(chunk as Buffer))
        res.on('end', () => {
          try {
            const json = JSON.parse(Buffer.concat(chunks).toString('utf8'))
            const list = Array.isArray(json.tunnels) ? json.tunnels : []
            for (const tunnel of list) {
              const addr = String(tunnel?.config?.addr || '')
              const publicUrl = String(tunnel?.public_url || '')
              if (!publicUrl.startsWith('https://')) continue
              if (addr.endsWith(':' + port) || addr.endsWith(`localhost:${port}`) || addr === String(port)) {
                resolve(publicUrl)
                return
              }
            }
            resolve(null)
          } catch {
            resolve(null)
          }
        })
      }
    )
    request.on('error', () => resolve(null))
    request.on('timeout', () => {
      request.destroy()
      resolve(null)
    })
  })
}

export class TunnelManager {
  private child: ChildProcessWithoutNullStreams | null = null
  private adopted = false
  private snapshot: TunnelSnapshot = {
    phase: 'stopped',
    publicUrl: null,
    error: null,
    ngrokPath: null,
    ngrokVersion: null,
    authed: false,
    domain: null,
    log: []
  }
  private listeners = new Set<(snapshot: TunnelSnapshot) => void>()

  constructor(private readonly log: (level: 'info' | 'warn' | 'error', scope: string, message: string) => void) {}

  subscribe(listener: (snapshot: TunnelSnapshot) => void): () => void {
    this.listeners.add(listener)
    return () => this.listeners.delete(listener)
  }

  status(): TunnelSnapshot {
    return this.snapshot
  }

  private emit(patch: Partial<TunnelSnapshot>): void {
    this.snapshot = { ...this.snapshot, ...patch }
    for (const listener of this.listeners) listener(this.snapshot)
  }

  private appendLog(line: string): void {
    const trimmed = line.trim()
    if (!trimmed) return
    const log = [...this.snapshot.log, trimmed].slice(-120)
    this.emit({ log })
  }

  async start(options: TunnelOptions): Promise<TunnelSnapshot> {
    await this.stop(true)
    const detection = detectNgrok(options.ngrokPath)
    if (!detection.found || !detection.path) {
      this.emit({ phase: 'error', error: 'ngrok CLI not found. Install it from the Tunnel step.', ngrokPath: null })
      return this.snapshot
    }
    this.emit({
      phase: 'starting',
      error: null,
      ngrokPath: detection.path,
      ngrokVersion: detection.version,
      authed: detection.authed,
      domain: options.domain || null
    })

    if (options.authtoken && !detection.authed) {
      const result = configureAuthtoken(detection.path, options.authtoken)
      if (!result.ok) {
        this.emit({ phase: 'error', error: `Could not save the ngrok token: ${result.error}` })
        return this.snapshot
      }
      this.emit({ authed: true })
      this.log('info', 'tunnel', 'Saved ngrok authtoken')
    }

    // Adopt an agent the user already runs for this port (their old workflow).
    const adoptedUrl = await localApiTunnels(options.port)
    if (adoptedUrl) {
      this.adopted = true
      this.appendLog(`Adopted existing ngrok agent: ${adoptedUrl}`)
      this.emit({ phase: 'online', publicUrl: adoptedUrl, error: null })
      this.log('info', 'tunnel', `Using existing tunnel ${adoptedUrl}`)
      return this.snapshot
    }

    const args = ['http', String(options.port), '--log=stdout', '--log-format=json']
    if (options.domain) {
      const domain = options.domain.replace(/^https?:\/\//, '').replace(/\/+$/, '')
      args.push(`--url=https://${domain}`)
    }
    if (options.protect && options.protectToken) {
      const policyPath = writeTrafficPolicy(options.protectToken)
      if (existsSync(policyPath)) args.push(`--traffic-policy-file=${policyPath}`)
    }

    this.appendLog(`$ ngrok ${args.filter((arg) => !arg.startsWith('--traffic-policy')).join(' ')}`)
    const child = spawn(detection.path, args, { windowsHide: true })
    this.child = child
    this.adopted = false
    let found = false

    const handleLine = (raw: string): void => {
      for (const line of raw.split(/\r?\n/)) {
        if (!line.trim()) continue
        let text = line
        try {
          const json = JSON.parse(line)
          const candidate =
            (json.obj && (json.obj.url || json.obj.public_url)) ||
            (typeof json.msg === 'string' ? extractUrl(json.msg) : null)
          if (candidate) text = `${json.msg ? json.msg + ' ' : ''}${candidate}`
          if (json.lvl === 'eror' || json.lvl === 'error') {
            const message = String(json.err || json.msg || 'ngrok error')
            this.appendLog(`error: ${message}`)
            if (/ERR_NGROK_4018|authtoken/i.test(message)) {
              this.emit({
                phase: 'error',
                error: 'ngrok needs an authtoken. Paste it in the Tunnel step (dashboard.ngrok.com/get-started/your-authtoken).'
              })
            }
            continue
          }
        } catch {
          /* plain text log line */
        }
        const url = extractUrl(text)
        if (url && !found) {
          found = true
          this.emit({ phase: 'online', publicUrl: url, error: null })
          this.log('info', 'tunnel', `Tunnel online at ${url}`)
        } else if (/ERR_NGROK_\d+/.test(text)) {
          this.appendLog(text)
        }
      }
    }

    child.stdout.setEncoding('utf8')
    child.stderr.setEncoding('utf8')
    child.stdout.on('data', handleLine)
    child.stderr.on('data', handleLine)
    child.on('exit', (code, signal) => {
      const wasOnline = this.snapshot.phase === 'online'
      this.child = null
      if (this.snapshot.phase === 'starting' || wasOnline) {
        this.emit({
          phase: 'error',
          publicUrl: null,
          error: `ngrok exited (${signal || code}). ${this.snapshot.log.slice(-3).join(' ')}`.slice(0, 400)
        })
        this.log('warn', 'tunnel', `ngrok exited with code ${code}`)
      } else {
        this.emit({ phase: 'stopped', publicUrl: null })
      }
    })

    const deadline = Date.now() + 25_000
    while (!found && Date.now() < deadline) {
      await new Promise((resolve) => setTimeout(resolve, 500))
      if (!this.child) break
      if (this.snapshot.phase === 'error') break
      if (!found) {
        const late = await localApiTunnels(options.port, 500)
        if (late) {
          found = true
          this.emit({ phase: 'online', publicUrl: late, error: null })
        }
      }
    }
    if (!found && this.snapshot.phase !== 'online' && this.snapshot.phase !== 'error') {
      const hint = this.snapshot.authed
        ? 'Check the tunnel log below.'
        : 'no authtoken was configured yet: add it in the Tunnel step.'
      this.emit({ phase: 'error', error: `ngrok did not report a public URL (${hint})` })
    }
    return this.snapshot
  }

  async stop(silent = false): Promise<void> {
    const child = this.child
    this.child = null
    if (child && child.pid) {
      try {
        spawn('taskkill', ['/pid', String(child.pid), '/T', '/F'], { windowsHide: true })
      } catch {
        try {
          child.kill()
        } catch {
          /* ignore */
        }
      }
    }
    if (this.snapshot.phase !== 'stopped' || this.snapshot.publicUrl) {
      this.emit({ phase: 'stopped', publicUrl: null, error: null })
      if (!silent) this.log('info', 'tunnel', 'Tunnel stopped')
    }
  }

  isManaged(): boolean {
    return this.child !== null
  }

  isAdopted(): boolean {
    return this.adopted
  }
}

function extractUrl(text: string): string | null {
  const match = /https:\/\/[a-z0-9-]+(?:\.[a-z0-9-]+)*\.ngrok(?:-free)?\.(?:app|dev)/i.exec(text)
  return match ? match[0] : null
}
